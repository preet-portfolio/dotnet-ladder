using System.Text;
using System.Text.Json;
using Ladder.Json;
using Ladder.Json.Judge;

// Usage: Ladder.Json.Judge <JSONTestSuite/test_parsing dir> <results dir> <divergences.md path>
if (args.Length != 3)
{
    Console.Error.WriteLine("usage: Ladder.Json.Judge <test_parsing dir> <results dir> <divergences.md>");
    return 2;
}

string suiteDir = args[0];
string resultsDir = args[1];
Directory.CreateDirectory(resultsDir);

var stjOptions = new JsonDocumentOptions { MaxDepth = JsonTokenizer.MaxSupportedDepth };
var log = new StringBuilder();
var divergences = new StringBuilder();
int yPass = 0, yTotal = 0, nPass = 0, nTotal = 0, iAccept = 0, iTotal = 0, treeMismatches = 0;
var failures = new List<string>();
var informative = new List<string>();

foreach (string path in Directory.GetFiles(suiteDir, "*.json").Order(StringComparer.Ordinal))
{
    string name = Path.GetFileName(path);
    byte[] bytes = File.ReadAllBytes(path);

    bool ours = JsonDocumentParser.TryParse(bytes, out JsonValue? tree, out JsonParseError error);
    string oursText = ours ? "ACCEPT" : $"REJECT({error})";
    string tokenizerText = TokenizeOnly(bytes);

    // JsonDocument.Parse defers string transcoding, so a document can parse and then fail when a string is read.
    // Both steps are recorded: "parse" is what Parse returned, "read" is reading every string afterwards.
    JsonDocument? stjDoc = null;
    string stjText = "";
    try
    {
        stjDoc = JsonDocument.Parse(bytes, stjOptions);
    }
    catch (JsonException ex)
    {
        stjText = $"REJECT(parse:{ex.GetType().Name})";
    }

    if (stjDoc is not null)
    {
        try
        {
            _ = Canonical.Of(stjDoc.RootElement);
            stjText = "ACCEPT";
        }
        catch (InvalidOperationException)
        {
            stjDoc.Dispose();
            stjDoc = null;
            stjText = "parse:ACCEPT read:THROWS";
        }
    }

    string verdict;
    switch (name[0])
    {
        case 'y':
            yTotal++;
            verdict = ours ? "PASS" : "FAIL";
            if (ours)
            {
                yPass++;
            }

            break;
        case 'n':
            nTotal++;
            verdict = ours ? "FAIL" : "PASS";
            if (!ours)
            {
                nPass++;
            }

            break;
        default:
            iTotal++;
            verdict = "INFO";
            if (ours)
            {
                iAccept++;
            }

            informative.Add($"| `{name}` | {tokenizerText} | {oursText} | {stjText} |");
            break;
    }

    if (verdict == "FAIL")
    {
        failures.Add(name);
    }

    string treeNote = "";
    if (ours && stjDoc is not null)
    {
        string a = Canonical.Of(tree!);
        string b = Canonical.Of(stjDoc.RootElement);
        if (!string.Equals(a, b, StringComparison.Ordinal))
        {
            treeMismatches++;
            treeNote = " TREE-MISMATCH";
            divergences.AppendLine($"- `{name}`: trees differ\n  - ours: `{Truncate(a)}`\n  - stj:  `{Truncate(b)}`");
        }
    }
    else if (ours != (stjDoc is not null))
    {
        divergences.AppendLine($"- `{name}`: ours {oursText}, System.Text.Json {stjText}");
    }

    stjDoc?.Dispose();
    log.AppendLine($"{verdict,-4}  {name,-60} ours={oursText,-45} stj={stjText}{treeNote}");
}

log.AppendLine();
log.AppendLine($"y_ accepted: {yPass}/{yTotal}");
log.AppendLine($"n_ rejected: {nPass}/{nTotal}");
log.AppendLine($"i_ accepted: {iAccept}/{iTotal} (implementation-defined; listed in README)");
log.AppendLine($"tree mismatches vs System.Text.Json (both accepted): {treeMismatches}");
log.AppendLine($"failures: {(failures.Count == 0 ? "none" : string.Join(", ", failures))}");

string report = log.ToString();
Console.Write(report);
File.WriteAllText(Path.Combine(resultsDir, "jsontestsuite.txt"), report);
File.WriteAllText(
    args[2],
    "# Divergences from System.Text.Json on JSONTestSuite\n\n" +
    "Generated by `judge/run-judge.sh`. Listed as found; the parser was not changed to match.\n\n" +
    (divergences.Length == 0 ? "None.\n" : divergences.ToString()) +
    "\n## Implementation-defined (`i_`) files\n\nTokenizer = `JsonTokenizer` alone; tree = `JsonDocumentParser` (also decodes strings).\n\n| File | Our tokenizer | Our tree | System.Text.Json |\n|---|---|---|---|\n" +
    string.Join('\n', informative) + "\n");

return failures.Count == 0 ? 0 : 1;

static string TokenizeOnly(byte[] bytes)
{
    var tokenizer = new JsonTokenizer(bytes);
    while (tokenizer.Read())
    {
    }

    return tokenizer.Error.IsError ? $"REJECT({tokenizer.Error})" : "ACCEPT";
}

static string Truncate(string s) => s.Length <= 200 ? s : s[..200] + "…";
